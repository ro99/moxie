//! M2's exit clause: a whole working set, out of device memory, with its byte
//! and cost trace reconciled against the resource ledger.
//!
//! Two cases, and the pair is the deliverable rather than either one alone.
//!
//! * **`whole-set-decode`** runs a decode-shaped row batch through **every one
//!   of the designated artifact's 30 routed layers**, in two cache
//!   configurations, and requires every layer's device answer to equal the CPU
//!   candidate's over the same bytes. The roomy configuration is where the
//!   planner's prediction is an equality; the tight one is where it is a
//!   declared lower bound. Both reconcile exactly.
//! * **`whole-set-full`** demands **every expert of every routed layer** --
//!   45,675,970,560 B, 88.5% of the artifact and 1.77 times the largest card on
//!   this machine -- through a device cache holding sixteen of one layer's 128
//!   experts. It is the out-of-device-memory clause, and it needs no restricted
//!   budget argument to be one.
//!
//! **What is synthetic is said here, before any result.** The activations are
//! generated by this test and **the routes are written by this test**;
//! `whole-set-full`'s route is constructed so that its union is the whole expert
//! set. The **bytes are the artifact's own**, read from its shards at their real
//! offsets. This is not model support, no quality claim follows (O2), and no
//! route-distribution claim follows either.
//!
//! **`whole-set-full` is deliberately not compared against the CPU candidate**,
//! and the arithmetic rather than an adjective: its 3,840 row-expert products
//! are 2.28e10 multiply-adds, which at the rate this lane's debug host candidate
//! measures is about nine minutes per pass, and what it would buy is a repeat of
//! a comparison `whole-set-decode` already makes on every one of the 30 layers.
//! What it adds instead is bitwise equality of all three cards' answers to each
//! other, which also checks sm_86 against sm_120 and costs nothing.
//!
//! Skipped, loudly, when the artifact is not on this machine.
#![cfg(feature = "driver")]

