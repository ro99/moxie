/// The designated BF16 MoE. A read-only input: nothing here writes, copies,
/// converts or downloads anything.
const ARTIFACT: &str = "/fast/models/google/gemma-4-26B-A4B-it";
const SHARDS: [&str; 2] = [
    "model-00001-of-00002.safetensors",
    "model-00002-of-00002.safetensors",
];

const LAYERS: u32 = 30;
const HIDDEN: u64 = 2816;
const INTERMEDIATE: u64 = 704;
const EXPERTS: u64 = 128;
const TOP_K: u64 = 8;
const GATE_UP_PER_EXPERT: u64 = 2 * INTERMEDIATE * HIDDEN * 2;
const DOWN_PER_EXPERT: u64 = HIDDEN * INTERMEDIATE * 2;
const EXPERT_TOTAL: u64 = GATE_UP_PER_EXPERT + DOWN_PER_EXPERT;
/// One layer's 128 experts.
const LAYER_EXPERTS: u64 = EXPERTS * EXPERT_TOTAL;
/// Every routed layer's experts: the number M2's exit is about.
const WHOLE_SET: u64 = LAYERS as u64 * LAYER_EXPERTS;
const MIB: u64 = 1024 * 1024;

/// A `RankContext` is exclusive per device and `cargo test` runs a binary's
/// tests in parallel threads. Serialising them is not a workaround: the
/// exclusivity is the property task 0007 established deliberately.
static DEVICE: Mutex<()> = Mutex::new(());

fn one_at_a_time() -> MutexGuard<'static, ()> {
    DEVICE.lock().unwrap_or_else(|e| e.into_inner())
}

fn artifact_id() -> ArtifactId {
    // The artifact's own index digest, recorded in the bring-up record. Not a
    // path: the authority may not learn what one is.
    ArtifactId::new("sha256:907826a6e46ff454272bd6db1fee629d5531a2303be22986d825a0871d7dc7a7")
        .unwrap()
}

fn tensor_names(layer: u32) -> (String, String) {
    (
        format!("model.language_model.layers.{layer}.experts.gate_up_proj"),
        format!("model.language_model.layers.{layer}.experts.down_proj"),
    )
}

fn roles(layer: u32) -> ExpertRoles {
    ExpertRoles {
        artifact: artifact_id(),
        gate_up_role: format!("experts_gate_up.{layer}"),
        down_role: format!("experts_down.{layer}"),
        format_version: 1,
    }
}

/// Which shard holds each tensor, read from the shards' own headers.
///
/// Not assumed from the layer index: a two-shard split is a property of the
/// artifact, and guessing where the boundary falls is how a test comes to read
/// the wrong bytes confidently.
fn shard_of(shards: &[Shard], tensor: &str) -> usize {
    shards
        .iter()
        .position(|s| s.header().get(tensor).is_ok())
        .unwrap_or_else(|| panic!("no shard holds {tensor}"))
}

/// Every layer's two expert tensors, bound to the shard that holds them.
fn source(dir: &Path) -> ShardSource {
    let open = || -> Vec<Shard> {
        SHARDS
            .iter()
            .map(|name| Shard::open(&dir.join(name)).unwrap())
            .collect()
    };
    let probe = open();
    let mut src = ShardSource::new(artifact_id(), open());
    for layer in 0..LAYERS {
        let (gate_up, down) = tensor_names(layer);
        for (role, tensor) in [
            (format!("experts_gate_up.{layer}"), gate_up),
            (format!("experts_down.{layer}"), down),
        ] {
            let index = shard_of(&probe, &tensor);
            src = src.role(role, index, tensor).unwrap();
        }
    }
    src
}

fn mlp() -> OpParams {
    OpParams::ExpertMlp {
        hidden: HIDDEN,
        intermediate: INTERMEDIATE,
        experts: EXPERTS,
        top_k: TOP_K,
        // The artifact declares `gelu_pytorch_tanh`.
        activation: ExpertActivation::GeGlu,
    }
}

fn combine() -> OpParams {
    OpParams::Combine {
        hidden: HIDDEN,
        top_k: TOP_K,
        order: CombineOrder::AscendingExpertId,
        output_scale: 1.0,
    }
}

/// Deterministic BF16 activations. Synthetic, and that is the whole caveat.
fn activations(rows: u64, seed: u64) -> Vec<u8> {
    let mut state = seed | 1;
    let mut out = Vec::with_capacity((rows * HIDDEN * 2) as usize);
    for _ in 0..(rows * HIDDEN) {
        state = state
            .wrapping_mul(6364136223846793005)
            .wrapping_add(1442695040888963407);
        let unit = ((state >> 40) as f32) / ((1u32 << 24) as f32) - 0.5;
        out.extend_from_slice(&moxie_kernels::cpu_expert::to_bf16_bits(unit).to_le_bytes());
    }
    out
}

/// A decode-shaped route: two rows of top-k 8, distinct per layer.
///
/// Written by this test. The overlap between the two rows is what makes the
/// union smaller than `rows * top_k`, which is document 03's point about not
/// multiplying active experts by batch rows.
fn decode_route(layer: u32) -> Vec<u32> {
    let mut out = Vec::with_capacity((2 * TOP_K) as usize);
    let mut state = 0x0023_0000u64 | u64::from(layer);
    let mut taken: Vec<u32> = Vec::new();
    for row in 0..2 {
        let mut row_experts: Vec<u32> = Vec::new();
        while row_experts.len() < TOP_K as usize {
            state = state
                .wrapping_mul(6364136223846793005)
                .wrapping_add(1442695040888963407);
            let candidate = ((state >> 33) % EXPERTS) as u32;
            // Rows share their first three selections, so the union is smaller
            // than sixteen and reuse is real rather than assumed.
            let pick = if row == 1 && row_experts.len() < 3 {
                taken[row_experts.len()]
            } else {
                candidate
            };
            if !row_experts.contains(&pick) {
                row_experts.push(pick);
            }
        }
        if row == 0 {
            taken = row_experts.clone();
        }
        out.extend_from_slice(&row_experts);
    }
    out
}

/// A route whose union is the **whole** expert set: sixteen rows of eight,
/// partitioning 0..128.
fn full_route() -> Vec<u32> {
    (0..EXPERTS as u32).collect()
}

fn union_of(route: &[u32]) -> Vec<u32> {
    let mut out = route.to_vec();
    out.sort_unstable();
    out.dedup();
    out
}

