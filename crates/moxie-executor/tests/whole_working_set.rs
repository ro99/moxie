/// How much cache a configuration gives, as a ratio of what one layer demands.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Room {
    /// Enough for a whole layer at once: the branch where a prediction is an
    /// equality.
    Roomy,
    /// A quarter of it: the branch where eviction and backpressure make it a
    /// declared lower bound.
    Tight,
    /// One eighth of a whole layer -- sixteen of 128 experts -- which is what
    /// `whole-set-full` streams 45,675,970,560 B through.
    Eighth,
}

impl Room {
    fn of(self, union_bytes: u64) -> u64 {
        let align = |bytes: u64| bytes.div_ceil(256) * 256;
        match self {
            Room::Roomy => align(union_bytes),
            Room::Tight => align(union_bytes.div_ceil(4).max(EXPERT_TOTAL)),
            Room::Eighth => align(LAYER_EXPERTS / 8),
        }
    }
}

struct Config<'a> {
    case: &'a str,
    rows: u64,
    routes: Vec<Vec<u32>>,
    device: Option<&'a RankContext>,
    device_room: Room,
    host_room: Room,
}

struct StepResult {
    /// Every layer's slot buffer, in layer order.
    slots: Vec<Vec<u8>>,
    trace: StepTrace,
    demanded_bytes: u64,
    evictions: u64,
    drains: u64,
    elapsed: std::time::Duration,
}

/// Run one whole working set: every routed layer, one authority, one ledger.
fn run_whole_set(dir: &Path, config: &Config<'_>) -> StepResult {
    let x = activations(config.rows, 0x0021_2026);
    let catalogue = moxie_kernels::expert_mlp_catalogue();
    let device = config.device;
    let scope = device.map_or(Scope::Host, |ctx| Scope::Device(ctx.uuid()));

    // The caches are sized from the *first* layer's demand, so a configuration
    // named "roomy" means the same thing at every layer of a route whose union
    // varies.
    let first_union = union_of(&config.routes[0]).len() as u64 * EXPERT_TOTAL;
    let device_cache = config.device_room.of(first_union);
    let host_cache = config.host_room.of(first_union);

    let mut snapshots = vec![CapacitySnapshot::new(Scope::Host, 8 << 30, 256 * MIB).unwrap()];
    if let Some(ctx) = device {
        snapshots
            .push(CapacitySnapshot::new(Scope::Device(ctx.uuid()), 8 << 30, 256 * MIB).unwrap());
    }
    let mut ledger = Ledger::new(snapshots).unwrap();
    let mut request = ResidencyRequest::new(config.case, host_cache);
    if let Some(ctx) = device {
        request = request.device(ctx.uuid(), device_cache);
    }
    let mut authority = ResidencyAuthority::open(&mut ledger, &request).unwrap();
    let mut residency = device.map(|ctx| DeviceResidency::create(ctx, &mut authority).unwrap());
    let mut src = source(dir);

    let policy = ExpertPolicy {
        device: if device.is_some() {
            StrategyControl::Required
        } else {
            StrategyControl::Off
        },
        host: if device.is_some() {
            StrategyControl::Off
        } else {
            StrategyControl::Auto
        },
        host_placement: StrategyControl::Off,
        // The declared 1 MiB/row threshold sends every expert of this artifact
        // to the CPU -- task 0021 measured exactly that and asserts it -- so a
        // device case has to raise it, and says so rather than hiding it.
        max_transfer_bytes_per_row: EXPERT_TOTAL,
        ..ExpertPolicy::default()
    };

    let started = Instant::now();
    let mut layers: Vec<LayerTrace> = Vec::new();
    let mut slots: Vec<Vec<u8>> = Vec::new();
    let mut demanded = 0u64;
    for (layer, route) in config.routes.iter().enumerate() {
        let layer = layer as u32;
        let union = union_of(route);
        demanded += union.len() as u64 * EXPERT_TOTAL;
        let resident = resident_chunks(&authority, device.map(|_| scope), layer);
        let budget = ExpertBudget {
            device: device.map_or_else(
                || {
                    moxie_types::DeviceUuid::parse("GPU-00000000-0000-0000-0000-000000000000")
                        .unwrap()
                },
                RankContext::uuid,
            ),
            device_pci_bus_id: device
                .map_or_else(String::new, |c| c.capability().pci_bus_id.clone()),
            device_cache_cap_bytes: if device.is_some() { device_cache } else { 0 },
            device_cache_leased_bytes: 0,
            device_arena_free_bytes: if device.is_some() { 64 * MIB } else { 0 },
            host_workspace_bytes: 16 * MIB,
            host_buffer_bytes: 16 * MIB,
            host_cache_cap_bytes: host_cache,
            host_cache_leased_bytes: 0,
            resident,
        };
        let plan = compile_experts(
            &mlp(),
            &combine(),
            route,
            &budget,
            &policy,
            None,
            device.map(|ctx| ExpertKernels {
                capability: ctx.capability(),
                catalogue: &catalogue,
            }),
        )
        .unwrap();
        assert_eq!(plan.groups().len(), union.len(), "layer {layer}");

        let snapshot = LayerSnapshot::take(layer, &authority);
        let mut run = GroupedRun::admit(&mut ledger, plan, roles(layer), None).unwrap();
        if let (Some(ctx), Some(residency)) = (device, residency.as_mut()) {
            run.attach_device(&mut ledger, ctx, residency).unwrap();
        }
        run.load_activations(&x).unwrap();
        run.run_to_completion(
            &mut authority,
            &mut src,
            TurnId::new(u64::from(layer) + 1),
            0,
            u64::MAX,
        )
        .unwrap();
        layers.push(snapshot.close(&run, &authority, &ledger));
        slots.push(run.buffers().slots().to_vec());
        run.close(&mut ledger).unwrap();
        authority.end_turn(TurnId::new(u64::from(layer) + 1));
    }
    let elapsed = started.elapsed();
    let stats = authority.stats();
    let drains: u64 = layers.iter().map(|l| l.cost.backpressure_drains).sum();

    authority.retire_all(Scope::Host);
    if device.is_some() {
        authority.retire_all(scope);
    }
    if let (Some(residency), Some(_)) = (residency, device) {
        residency.close(&mut authority).unwrap();
    }
    authority.close(&mut ledger).unwrap();
    let trace = StepTrace::new(
        artifact_id().as_str(),
        config.case,
        layers,
        &authority,
        &ledger,
    );
    assert!(ledger.outstanding().is_empty());

    StepResult {
        slots,
        trace,
        demanded_bytes: demanded,
        evictions: stats.evictions,
        drains,
        elapsed,
    }
}

/// Where this layer's expert chunks are, read from the authority per chunk.
fn resident_chunks(
    authority: &ResidencyAuthority,
    device_scope: Option<Scope>,
    layer: u32,
) -> ResidentChunks {
    let roles = [
        format!("experts_gate_up.{layer}"),
        format!("experts_down.{layer}"),
    ];
    let mut out = ResidentChunks::none();
    let mut seen: Vec<(u32, u64)> = Vec::new();
    for chunk in authority.outstanding() {
        if !chunk.state.is_ready() {
            continue;
        }
        let Some(expert) = chunk.chunk.slot().expert_index() else {
            continue;
        };
        if !roles.iter().any(|r| r == chunk.chunk.slot().role()) {
            continue;
        }
        let on_device = Some(chunk.scope) == device_scope;
        let in_host = chunk.scope == Scope::Host;
        let key = (expert, chunk.bytes);
        if let Some(index) = seen.iter().position(|k| *k == key) {
            let entry = &mut out.chunks_mut()[index];
            entry.on_device |= on_device;
            entry.in_host |= in_host;
        } else {
            seen.push(key);
            out.push(ChunkResidency {
                expert,
                bytes: chunk.bytes,
                on_device,
                in_host,
            });
        }
    }
    out
}

fn artifact_dir() -> Option<PathBuf> {
    let dir = PathBuf::from(ARTIFACT);
    dir.is_dir().then_some(dir)
}

// ---------------------------------------------------------------------------
// whole-set-decode: every layer, against the reference, in both cache
// configurations
// ---------------------------------------------------------------------------

#[test]
fn the_whole_working_set_runs_on_every_gpu_and_matches_the_cpu_candidate() {
    let _serial = one_at_a_time();
    let Some(dir) = artifact_dir() else {
        println!(
            "SKIPPED: {ARTIFACT} is not present on this machine; the trace itself is swept \
                  over synthetic fixtures in working_set_trace.rs"
        );
        return;
    };
    let count = moxie_cuda::device_count().unwrap();
    assert!(count > 0, "the device lane requires real hardware");

    let routes: Vec<Vec<u32>> = (0..LAYERS).map(decode_route).collect();
    let unions: Vec<usize> = routes.iter().map(|r| union_of(r).len()).collect();
    let demanded: u64 = unions.iter().map(|u| *u as u64 * EXPERT_TOTAL).sum();
    println!(
        "whole-set-decode: {LAYERS} routed layer(s), 2 row(s) of top-k {TOP_K}, unions {:?}, \
         {demanded} B demanded",
        unions
    );

    // The reference, computed **once**: the CPU candidate is bit-identical to
    // task 0019's oracle (proven separately), and its answer does not depend on
    // which card the device candidate ran on.
    let reference = run_whole_set(
        &dir,
        &Config {
            case: "whole-set-decode/reference",
            rows: 2,
            routes: routes.clone(),
            device: None,
            device_room: Room::Roomy,
            host_room: Room::Roomy,
        },
    );
    reference
        .trace
        .reconcile()
        .expect("the host reference's own trace reconciles");
    println!(
        "  cpu candidate: {} layer(s) in {:.2?} (debug build, one run, NOT a benchmark)",
        reference.slots.len(),
        reference.elapsed
    );

    let mut checked = 0u32;
    for ordinal in 0..count {
        let ctx = RankContext::acquire(RankId(0), ordinal).unwrap();
        for room in [Room::Roomy, Room::Tight] {
            let result = run_whole_set(
                &dir,
                &Config {
                    case: "whole-set-decode",
                    rows: 2,
                    routes: routes.clone(),
                    device: Some(&ctx),
                    device_room: room,
                    host_room: room,
                },
            );
            let report = result
                .trace
                .reconcile()
                .unwrap_or_else(|e| panic!("{} {room:?} did not reconcile: {e}", ctx.uuid()));
            assert_eq!(result.demanded_bytes, demanded);
            assert_eq!(result.slots.len(), LAYERS as usize);
            for (layer, (got, want)) in result.slots.iter().zip(reference.slots.iter()).enumerate()
            {
                assert_eq!(
                    got,
                    want,
                    "layer {layer} on {} disagrees with the CPU candidate over the same bytes",
                    ctx.uuid()
                );
            }
            // Each configuration must actually be the branch it is named for.
            let exact = result
                .trace
                .layers
                .iter()
                .filter(|l| matches!(l.predicted.exactness, Exactness::Exact))
                .count();
            match room {
                Room::Roomy => assert_eq!(
                    exact, LAYERS as usize,
                    "a roomy cache produced a lower bound: the exact branch is untested"
                ),
                _ => assert_eq!(
                    exact, 0,
                    "a tight cache produced an exact prediction: the bound branch is untested"
                ),
            }
            if room == Room::Tight {
                assert!(result.evictions > 0, "a tight cache never evicted");
                assert!(result.drains > 0, "a tight cache never refused the queue");
            }
            checked += report.equalities_checked;
            println!(
                "  {} {room:?}: {} equality check(s) ({} lower bound), {} eviction(s), {} \
                 backpressure drain(s), {:.2?}",
                ctx.uuid(),
                report.equalities_checked,
                report.bounds_checked,
                result.evictions,
                result.drains,
                result.elapsed
            );
        }
    }
    println!(
        "  {checked} equality check(s) across {count} card(s); all {} layer(s) bitwise equal to \
         the CPU candidate on every card",
        LAYERS
    );
    println!(
        "NOT model support: the activations are synthetic and the routes are written by this test. \
         Output quality is O2."
    );
}

// ---------------------------------------------------------------------------
// whole-set-full: the artifact's entire routed payload, out of device memory
// ---------------------------------------------------------------------------

#[test]
fn the_artifacts_whole_expert_payload_streams_through_a_restricted_cache() {
    let _serial = one_at_a_time();
    let Some(dir) = artifact_dir() else {
        println!("SKIPPED: {ARTIFACT} is not present on this machine");
        return;
    };
    let count = moxie_cuda::device_count().unwrap();
    assert!(count > 0, "the device lane requires real hardware");

    // Sixteen rows of eight, partitioning the expert set: the union is all 128.
    let route = full_route();
    assert_eq!(union_of(&route).len(), EXPERTS as usize);
    let routes: Vec<Vec<u32>> = (0..LAYERS).map(|_| route.clone()).collect();

    let device_cache = Room::Eighth.of(LAYER_EXPERTS);
    println!(
        "whole-set-full: {WHOLE_SET} B of expert weights over {LAYERS} layer(s) -- 88.5% of the \
         artifact -- through a {device_cache} B device cache holding {} of 128 experts",
        device_cache / EXPERT_TOTAL
    );

    let mut answers: Vec<(String, Vec<Vec<u8>>)> = Vec::new();
    for ordinal in 0..count {
        let ctx = RankContext::acquire(RankId(0), ordinal).unwrap();
        let result = run_whole_set(
            &dir,
            &Config {
                case: "whole-set-full",
                rows: EXPERTS / TOP_K,
                routes: routes.clone(),
                device: Some(&ctx),
                device_room: Room::Eighth,
                host_room: Room::Tight,
            },
        );
        let report = result
            .trace
            .reconcile()
            .unwrap_or_else(|e| panic!("{} did not reconcile: {e}", ctx.uuid()));
        assert_eq!(
            result.demanded_bytes, WHOLE_SET,
            "the whole routed payload was not demanded"
        );
        let admitted: u64 = result
            .trace
            .totals
            .iter()
            .filter(|(scope, _)| matches!(scope, Scope::Device(_)))
            .map(|(_, flow)| flow.admitted_bytes)
            .sum();
        assert!(
            admitted >= WHOLE_SET,
            "the device admitted {admitted} B of a {WHOLE_SET} B working set"
        );
        assert!(
            result.evictions > 0,
            "a cache holding 16 of 128 experts served the whole set without evicting"
        );
        // Backpressure is **not** asserted here, and the reason is worth a line:
        // a queue four deep pins four of the sixteen experts this cache holds, so
        // there is room to admit the fifth and the authority never refuses. That
        // is a property of the queue against the cache, not of the working set,
        // and it is `whole-set-decode/Tight` and task 0022 that exercise a
        // refusal. The count is printed because it is a fact about this run.
        println!(
            "  {}: {admitted} B admitted, {} eviction(s), {} backpressure drain(s), {} equality \
             check(s), {:.2?} (debug build, one run, NOT a benchmark)",
            ctx.uuid(),
            result.evictions,
            result.drains,
            report.equalities_checked,
            result.elapsed
        );
        answers.push((ctx.uuid().to_string(), result.slots));
    }

    // Bitwise equality across the cards, which is also sm_86 against sm_120.
    let (first_name, first) = &answers[0];
    for (name, other) in answers.iter().skip(1) {
        for (layer, (a, b)) in first.iter().zip(other.iter()).enumerate() {
            assert_eq!(a, b, "layer {layer}: {first_name} and {name} disagree");
        }
    }
    let components: usize = first.iter().map(|s| s.len() / 2).sum();
    println!(
        "  {components} BF16 slot component(s) equal across {} card(s)",
        answers.len()
    );
    println!(
        "NOT model support: the activations are synthetic and the route is written by this test, \
         constructed so that its union is the whole expert set. Output quality is O2."
    );
}
